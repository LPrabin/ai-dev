#!/usr/bin/env bash
# adapter-opencode.sh
# OpenCode reads AGENTS.md natively. This writes a global system prompt
# to ~/.config/opencode/system.md if the config dir exists.
#
# Called by: build-context --adapter opencode

set -euo pipefail

GLOBAL_CONTEXT="${1:-${AI_HOME:-$HOME/.ai}/prompts/global.md}"

# OpenCode config locations (try both XDG and legacy)
if [[ -n "${XDG_CONFIG_HOME:-}" ]]; then
  OC_DIR="${XDG_CONFIG_HOME}/opencode"
else
  OC_DIR="$HOME/.config/opencode"
fi

SYSTEM_FILE="${OC_DIR}/system.md"

[[ -f "$GLOBAL_CONTEXT" ]] || {
  echo "[adapter-opencode] error: context file not found: ${GLOBAL_CONTEXT}" >&2
  exit 1
}

mkdir -p "$OC_DIR"

cat > "$SYSTEM_FILE" <<'HEADER'
# OpenCode — Global System Prompt
# Auto-generated by ai-dev. Edit ~/.ai/context/ then run: build-context --adapter opencode

HEADER

cat "$GLOBAL_CONTEXT" >> "$SYSTEM_FILE"

echo "[adapter-opencode] wrote: ${SYSTEM_FILE} ($(wc -l < "$SYSTEM_FILE") lines)"
echo "[adapter-opencode] note: OpenCode reads AGENTS.md per-project natively."

# Distribute skills from ~/.ai-dev/skills/ to ~/.config/opencode/skills/
AI_SKILLS="${AI_HOME:-$HOME/.ai-dev}/bin/ai-skills"
if [[ -x "$AI_SKILLS" ]]; then
  "$AI_SKILLS" distribute opencode
else
  echo "[adapter-opencode] warning: ai-skills not found, skipping skills distribution" >&2
fi
