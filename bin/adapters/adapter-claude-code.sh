#!/usr/bin/env bash
# adapter-claude-code.sh
# Writes ~/.claude/CLAUDE.md from the assembled global context.
# Claude Code reads this file automatically for every session.
#
# Called by: build-context --adapter claude-code
# Args:      $1 = path to assembled global.md

set -euo pipefail

GLOBAL_CONTEXT="${1:-${AI_HOME:-$HOME/.ai}/prompts/global.md}"
CLAUDE_DIR="$HOME/.claude"
CLAUDE_GLOBAL="$CLAUDE_DIR/CLAUDE.md"

[[ -f "$GLOBAL_CONTEXT" ]] || {
  echo "[adapter-claude-code] error: context file not found: ${GLOBAL_CONTEXT}" >&2
  echo "Run: build-context first" >&2
  exit 1
}

mkdir -p "$CLAUDE_DIR"

# Claude Code also supports a commands/ dir for slash commands.
# We generate lightweight wrappers that delegate to our shell scripts.
mkdir -p "${CLAUDE_DIR}/commands"

# Write CLAUDE.md — pulls in the full global context
cat > "$CLAUDE_GLOBAL" <<'HEADER'
# Claude Code — Global Configuration
# Auto-generated by ai-dev/adapters/adapter-claude-code.sh
# Edit source files in ~/.ai/context/ then run: build-context --adapter claude-code

HEADER

cat "$GLOBAL_CONTEXT" >> "$CLAUDE_GLOBAL"

cat >> "$CLAUDE_GLOBAL" <<'FOOTER'

---

## Claude Code specifics

### Session start
1. Read AGENTS.md in the project root.
2. Run: `obs-read` in the terminal to pull Obsidian context.
3. Summarize in 3–5 lines. Ask for the goal if none is stated.

### Session end
Run: `obs-write` to log decisions to Obsidian.

### Available shell commands
- `obs-read`    — load Obsidian context
- `obs-write`   — write session notes to Obsidian
- `ai-review`   — linters + AI code review
- `ai-ship`     — pre-ship checklist
- `ai-debug`    — systematic debug protocol
- `obs-search`  — search Obsidian for past decisions

FOOTER

echo "[adapter-claude-code] wrote: ${CLAUDE_GLOBAL} ($(wc -l < "$CLAUDE_GLOBAL") lines)"

# Generate slash command stubs
# Claude Code reads .md files from ~/.claude/commands/ as /command-name
for cmd in review ship debug; do
  cmd_file="${CLAUDE_DIR}/commands/${cmd}.md"
  script_name="ai-${cmd}"
  cat > "$cmd_file" <<EOF
# /${cmd}

Runs the \`${script_name}\` shell script, which handles all mechanical work,
then provides AI analysis of the output.

\`\`\`bash
${script_name}
\`\`\`

After the script completes, review its output and flag any issues it missed.
EOF
done

# obs commands
for cmd in read write search; do
  cmd_file="${CLAUDE_DIR}/commands/obs-${cmd}.md"
  cat > "$cmd_file" <<EOF
# /obs-${cmd}

\`\`\`bash
obs-${cmd}
\`\`\`
EOF
done

echo "[adapter-claude-code] wrote command stubs to: ${CLAUDE_DIR}/commands/"

# Distribute MCP servers via `claude mcp add-json` CLI
MCP_REGISTRY="${AI_HOME:-$HOME/.ai}/context/mcp-servers.json"
if [[ -f "$MCP_REGISTRY" ]] && command -v jq >/dev/null 2>&1 && command -v claude >/dev/null 2>&1; then
  MCP_COUNT=0

  for name in $(jq -r '.servers | to_entries[] | select(.value.enabled) | .key' "$MCP_REGISTRY"); do
    claude mcp remove "$name" >/dev/null 2>&1 || true

    has_url=$(jq -r --arg n "$name" '.servers[$n].url // empty' "$MCP_REGISTRY")
    if [[ -n "$has_url" ]]; then
      server_json=$(jq -c --arg n "$name" '{
        type: "http", url: .servers[$n].url
      } + (if (.servers[$n].headers // {} | length) > 0
           then { headers: .servers[$n].headers } else {} end)' "$MCP_REGISTRY")
    else
      server_json=$(jq -c --arg n "$name" '{
        type: "stdio", command: .servers[$n].command, args: (.servers[$n].args // [])
      } + (if (.servers[$n].env // {} | length) > 0
           then { env: .servers[$n].env } else {} end)' "$MCP_REGISTRY")
    fi

    claude mcp add-json "$name" "$server_json" >/dev/null 2>&1
    MCP_COUNT=$((MCP_COUNT + 1))
  done

  echo "[adapter-claude-code] added ${MCP_COUNT} MCP server(s) via claude mcp add-json"
fi

# Distribute skills from ~/.ai-dev/skills/ to ~/.claude/skills/
AI_SKILLS="${AI_HOME:-$HOME/.ai-dev}/bin/ai-skills"
if [[ -x "$AI_SKILLS" ]]; then
  "$AI_SKILLS" distribute claude-code
else
  echo "[adapter-claude-code] warning: ai-skills not found, skipping skills distribution" >&2
fi
