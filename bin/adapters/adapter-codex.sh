#!/usr/bin/env bash
# adapter-codex.sh
# Codex CLI reads AGENTS.md natively and supports a global instructions file.
# This writes ~/.codex/instructions.md from the global context.
#
# Called by: build-context --adapter codex

set -euo pipefail

GLOBAL_CONTEXT="${1:-${AI_HOME:-$HOME/.ai}/prompts/global.md}"
CODEX_DIR="$HOME/.codex"
CODEX_INSTRUCTIONS="$CODEX_DIR/instructions.md"

[[ -f "$GLOBAL_CONTEXT" ]] || {
  echo "[adapter-codex] error: context file not found: ${GLOBAL_CONTEXT}" >&2
  exit 1
}

mkdir -p "$CODEX_DIR"

cat > "$CODEX_INSTRUCTIONS" <<'HEADER'
# Codex — Global Instructions
# Auto-generated by ai-dev. Edit ~/.ai/context/ then run: build-context --adapter codex

HEADER

cat "$GLOBAL_CONTEXT" >> "$CODEX_INSTRUCTIONS"

cat >> "$CODEX_INSTRUCTIONS" <<'FOOTER'

---

## Session workflow
- Project context lives in AGENTS.md (project root). Read it at session start.
- Run `obs-read` to pull Obsidian memory.
- Run `obs-write` at session end.
- Before committing: `ai-review`
- Before merging: `ai-ship`
FOOTER

echo "[adapter-codex] wrote: ${CODEX_INSTRUCTIONS} ($(wc -l < "$CODEX_INSTRUCTIONS") lines)"

# Distribute skills from ~/.ai-dev/skills/ to ~/.codex/skills/
AI_SKILLS="${AI_HOME:-$HOME/.ai-dev}/bin/ai-skills"
if [[ -x "$AI_SKILLS" ]]; then
  "$AI_SKILLS" distribute codex
else
  echo "[adapter-codex] warning: ai-skills not found, skipping skills distribution" >&2
fi
